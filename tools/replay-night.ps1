param(
    [Parameter(Mandatory = $true)][string[]]$Files,   # night protocol files in order: BAK first, then TXT
    [Parameter(Mandatory = $true)][string]$Key,       # developer key (path, see CLAUDE.local.md)
    [string]$Garmin = "",                             # optional: Garmin's stages, lines "from-minute to-minute stage"
    [string]$Model = "",                              # optional: a MODEL line to use instead of the one at START
    [int]$DeadlineMinute = -1,                        # optional: try another wake time (minutes after the start)
    [int]$WindowMinutes = 30,                         # wake window for -DeadlineMinute and -Sweep
    [switch]$Sweep                                    # try a wake time every 10 minutes and list the wake-ups
)
# Replays a recorded night through the current sleep engine in the simulator and
# compares the stages with the protocol and, if given, with Garmin's stages.
# The night data is written to logs/replay (git-ignored), never into source/.
# Example:
#   tools/replay-night.ps1 -Files logs/<night>/SmartWake-release.BAK,logs/<night>/SmartWake-release.TXT `
#       -Garmin logs/<night>/garmin-stages.txt -Key <developer key>
$ErrorActionPreference = "Stop"
$root = Split-Path $PSScriptRoot -Parent
$sdk = (Get-Content "$env:APPDATA\Garmin\ConnectIQ\current-sdk.cfg" -TotalCount 1).Trim()

# --- read the protocol: the last night that has minute lines
$lines = @()
foreach ($f in $Files) { $lines += Get-Content $f }
$lines = $lines | ForEach-Object { $_.Trim() }
$starts = @()
for ($i = 0; $i -lt $lines.Count; $i++) { if ($lines[$i] -match '^SW START') { $starts += $i } }
if ($starts.Count -eq 0) { throw "No START line found." }
$block = $null
for ($k = $starts.Count - 1; $k -ge 0; $k--) {
    $from = $starts[$k]
    $to = $(if ($k + 1 -lt $starts.Count) { $starts[$k + 1] - 1 } else { $lines.Count - 1 })
    $part = $lines[$from..$to]
    if ($part | Where-Object { $_ -match '^SW D\d+:' }) { $block = $part; break }
}
if (-not $block) { throw "No night with minute lines found." }

if ($block[0] -notmatch 't=(\d+) dl=(\d+) ws=(\d+) sens=(\d+)') { throw "Cannot read the START line: $($block[0])" }
$t0 = $Matches[1]; $dl = $Matches[2]; $ws = $Matches[3]; $sens = $Matches[4]
if ($DeadlineMinute -ge 0) {
    $dl = [long]$t0 + 60 * $DeadlineMinute
    $ws = $dl - 60 * $WindowMinutes
}
$modelLine = $(if ($Model) { $Model } else { ($block | Where-Object { $_ -match '^SW MODEL' } | Select-Object -First 1) })
$ring = $block | Where-Object { $_ -match '^SW RING' } | Select-Object -First 1

$dlines = @{}
foreach ($l in $block) { if ($l -match '^SW D(\d+):(.*)$') { $dlines[[int]$Matches[1]] = $Matches[2] } }
$payload = ($dlines.Keys | Sort-Object | ForEach-Object { '        "' + $dlines[$_] + '"' }) -join ",`n"

# --- learned profile at the start of that night
$model = ""
if ($modelLine) {
    $inv = [Globalization.CultureInfo]::InvariantCulture
    $flt = { param($v) ([double]::Parse($v, $inv)).ToString("0.0###", $inv) }
    $vals = @{}
    foreach ($m in [regex]::Matches($modelLine, '(\w+)=([-\d.,]+)')) { $vals[$m.Groups[1].Value] = $m.Groups[2].Value }
    $map = @{ hr = 'minHr'; hs = 'hrStd'; rm = 'rmssd'; st = 'stress'; rr = 'resp'; lh = 'lightHr'; cy = 'cycleMin'; sh = 'shift' }
    foreach ($k in $map.Keys) { if ($vals.ContainsKey($k)) { $model += "    model.$($map[$k]) = $(& $flt $vals[$k]);`n" } }
    if ($vals.ContainsKey('w')) {
        $w = ($vals['w'] -split ',' | ForEach-Object { ([double]::Parse($_, $inv) / 100).ToString("0.0###", $inv) }) -join ', '
        $model += "    model.weights = [$w] as Array<Float>;`n"
    }
}

# --- Garmin's stages as one letter per minute
$ref = ""
if ($Garmin) {
    $letters = @{ tief = 't'; leicht = 'l'; rem = 'r'; wach = 'w' }
    $chars = New-Object char[] 2000
    for ($i = 0; $i -lt $chars.Length; $i++) { $chars[$i] = '?' }
    $max = 0
    foreach ($l in Get-Content $Garmin) {
        if ($l -match '^\s*(\d+)\s+(\d+)\s+(\w+)') {
            for ($i = [int]$Matches[1]; $i -lt [int]$Matches[2]; $i++) { $chars[$i] = $letters[$Matches[3]] }
            if ([int]$Matches[2] -gt $max) { $max = [int]$Matches[2] }
        }
    }
    $ref = -join $chars[0..($max - 1)]
}

# --- generated test and jungle in logs/replay
$call = "replayNight(lines, $t0, $ws, $dl, $sens, model, `"$ref`");"
if ($Sweep) {
    $last = [int]($dlines.Keys | Measure-Object -Maximum | Select-Object -ExpandProperty Maximum)
    $total = $last + $dlines[$last].Length / 7
    $call = "replaySweep(lines, $t0, $sens, model, `"$ref`", 60, $([int]$total), 10, $WindowMinutes);"
}
$dir = Join-Path $root "logs\replay"
New-Item -ItemType Directory -Force $dir | Out-Null
$code = @"
import Toybox.Lang;
import Toybox.Test;

// Generated by tools/replay-night.ps1. Private night data: stays in logs/, never commit.
(:test)
function testReplayNight(logger as Test.Logger) as Boolean {
    var model = new SleepModel();
    model.persist = false;
$model    var lines = [
$payload
    ] as Array<String>;
    $call
    return true;
}
"@
$utf8 = New-Object System.Text.UTF8Encoding $false
[System.IO.File]::WriteAllText((Join-Path $dir "ReplayNight.mc"), $code, $utf8)
$jungle = "project.manifest = ../../manifest.xml`nbase.sourcePath = ../../source;.`nbase.resourcePath = ../../resources`n"
[System.IO.File]::WriteAllText((Join-Path $dir "replay.jungle"), $jungle, $utf8)

# --- build and run in the simulator
Push-Location $root
try {
    & "$sdk\bin\monkeyc.bat" -f logs/replay/replay.jungle -d fr265 -o bin/SmartWake-replay.prg -y $Key -w --unit-test
    if ($LASTEXITCODE -ne 0) { throw "Build failed." }
    if (-not (Get-Process simulator -ErrorAction SilentlyContinue)) {
        Start-Process "$sdk\bin\simulator.exe"
        Start-Sleep -Seconds 8
    }
    "night: start=$t0 window=$ws deadline=$dl sens=$sens"
    if ($ring) { "protocol: $ring" }
    if ($modelLine) { "profile: $modelLine" }
    & "$sdk\bin\monkeydo.bat" bin/SmartWake-replay.prg fr265 /t testReplayNight |
        Where-Object { $_ -match 'REPLAY|FAIL|ERROR|Error' } | ForEach-Object { $_ -replace '^.*?REPLAY ', '' }
} finally {
    Pop-Location
}
